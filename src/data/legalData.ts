export function createInitialSampleHistory(
  profile: OwnerProfile,
  company: ManagementCompany
): SavedClaim[] {
  const now = new Date();
  const d1 = new Date(now.getTime() - 1000 * 60 * 60 * 24 * 1);
  const d2 = new Date(now.getTime() - 1000 * 60 * 60 * 24 * 1 - 1000 * 60 * 8);
  const d3 = new Date(now.getTime() - 1000 * 60 * 60 * 24 * 1 - 1000 * 60 * 9);

  const heatingTpl = CLAIM_CATEGORIES.find((c) => c.id === 'heating')!.templates[0];
  const universalTpl = CLAIM_CATEGORIES.find((c) => c.id === 'universal')!.templates[0];
  const metersTpl = CLAIM_CATEGORIES.find((c) => c.id === 'meters')!.templates[0];

  const hBody = heatingTpl.bodyBuilder({
    details: 'радиаторы отопления полностью холодные, циркуляция теплоносителя отсутствует',
  });
  const uBody = universalTpl.bodyBuilder({
    details:
      'управляющая организация нарушает обязательства по надлежащему управлению и содержанию МКД',
  });
  const mBody = metersTpl.bodyBuilder({
    details:
      'приборы учета установлены, заявка на опломбировку подана, однако представитель УК для ввода в эксплуатацию не явился',
  });

  return [
    {
      id: 'sample-1',
      categoryId: 'heating',
      categoryLabel: 'Отопление',
      templateId: heatingTpl.id,
      title: 'Отсутствует отопление / холодные батареи',
      subject: heatingTpl.subject,
      documentText: buildOfficialClaimText({
        profile,
        company,
        title: heatingTpl.title,
        legalBasis: heatingTpl.legalBasis,
        facts: hBody.facts,
        demands: hBody.demands,
        date: d1,
      }),
      createdAt: d1.toISOString(),
      deadlineAt: addBusinessDays(d1, 10).toISOString(),
    },
    {
      id: 'sample-2',
      categoryId: 'universal',
      categoryLabel: 'Свой вопрос',
      templateId: universalTpl.id,
      title: 'Индивидуальное обращение / требование',
      subject: universalTpl.subject,
      documentText: buildOfficialClaimText({
        profile,
        company,
        title: universalTpl.title,
        legalBasis: universalTpl.legalBasis,
        facts: uBody.facts,
        demands: uBody.demands,
        date: d2,
      }),
      createdAt: d2.toISOString(),
      deadlineAt: addBusinessDays(d2, 10).toISOString(),
    },
    {
      id: 'sample-3',
      categoryId: 'meters',
      categoryLabel: 'Счетчики',
      templateId: metersTpl.id,
      title: 'ИПУ установлены, но не опломбированы',
      subject: metersTpl.subject,
      documentText: buildOfficialClaimText({
        profile,
        company,
        title: metersTpl.title,
        legalBasis: metersTpl.legalBasis,
        facts: mBody.facts,
        demands: mBody.demands,
        date: d3,
      }),
      createdAt: d3.toISOString(),
      deadlineAt: addBusinessDays(d3, 10).toISOString(),
    },
  ];
}
