function makeTemplate(params: {
  id: string;
  categoryId: ClaimCategoryId;
  title: string;
  hint: string;
  subject: string;
  legalBasis: string;
  defaultDetails: string;
  factPrefix: string;
  demands: string[];
}): ClaimTemplate {
  return {
    id: params.id,
    categoryId: params.categoryId,
    title: params.title,
    shortDescription: params.hint,
    subject: params.subject,
    legalBasis: params.legalBasis,
    fields: [
      {
        id: 'details',
        label: 'Текст описания проблемы',
        placeholder: params.hint,
        type: 'textarea',
        defaultValue: params.defaultDetails,
      },
    ],
    bodyBuilder: (v) => ({
      facts: `${params.factPrefix}: ${v.details?.trim() || params.defaultDetails}.`,
      demands: params.demands,
    }),
  };
}

